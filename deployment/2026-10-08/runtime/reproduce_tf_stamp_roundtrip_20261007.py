#!/usr/bin/env python3
"""Offline installed tf2_py time-bridge audit. No node, listener or master calls."""
import argparse
import hashlib
import json
import math
from pathlib import Path

def sha(path):return hashlib.sha256(Path(path).read_bytes()).hexdigest()

def main():
    p=argparse.ArgumentParser();p.add_argument('--input-report',type=Path,required=True);p.add_argument('--output',type=Path,required=True);a=p.parse_args()
    external=Path('/media/zhuyupei/SanStand/实验记录/Robot-Controller').resolve()
    if external not in a.input_report.resolve().parents or external not in a.output.resolve().parents or a.output.exists():raise ValueError('new external output and original external input required')
    original_hash=sha(a.input_report);original=json.loads(a.input_report.read_text())
    import rospy
    import tf2_py
    if rospy.core.is_initialized():raise RuntimeError('must run without a ROS node')
    buffer=tf2_py.BufferCore();rows=[]
    for recorded in original['rows']:
        ns=recorded['source_stamp_ns'];sec,nsec=divmod(ns,10**9)
        t=rospy.Time(sec,nsec);f=t.to_sec();whole=math.floor(f);fraction_ns=(f-whole)*1e9
        cpp=whole*10**9+math.floor(fraction_ns+.5)
        returned=buffer.lookup_transform_core('same','same',t).header.stamp.to_nsec()
        shifted=ns+37
        shifted_return=buffer.lookup_transform_core('same','same',rospy.Time(*divmod(shifted,10**9))).header.stamp.to_nsec()
        rows.append(dict(source_stamp_ns=ns,recorded_return_delta_ns=recorded['original_source_pose_evidence']['tf']['delta_ns'],
            float_seconds=f,float_seconds_hex=f.hex(),float_spacing_ns=2.**(math.frexp(f)[1]-53)*1e9,
            reconstructed_python_truncation_delta_ns=whole*10**9+int(fraction_ns)-ns,
            arithmetic_cpp_rounding_delta_ns=cpp-ns,installed_identity_lookup_delta_ns=returned-ns,
            deliberately_shifted_query_ns=shifted,shifted_identity_lookup_delta_ns=shifted_return-shifted))
    class Spy:
        secs=1791348020
        nsecs=123456789
        def __init__(self):self.calls=0
        def to_sec(self):
            self.calls+=1
            raise RuntimeError('LOCAL_ONLY_TO_SEC_PATH_PROOF')
    spy=Spy();exception=None
    try:buffer.lookup_transform_core('same','same',spy)
    except Exception as exc:exception=dict(type=type(exc).__name__,message=str(exc))
    sources=[Path(__file__).resolve(),Path('/opt/ros/noetic/lib/python3/dist-packages/tf2_py/_tf2.so'),
        Path('/opt/ros/noetic/lib/python3/dist-packages/tf2_ros/buffer.py'),
        Path('/opt/ros/noetic/lib/python3/dist-packages/rospy/rostime.py'),
        Path('/opt/ros/noetic/lib/python3/dist-packages/genpy/rostime.py'),
        Path('/opt/ros/noetic/include/ros/impl/time.h')]
    report=dict(schema=1,diagnostic_only=True,offline_only=True,input_report=str(a.input_report.resolve()),
        input_sha256=original_hash,input_unchanged=sha(a.input_report)==original_hash,rows=rows,
        sources={str(path):sha(path) for path in sources},installed_tf2_py_version='0.7.10',
        installed_converter_spy=dict(integer_secs_and_nsecs_attributes_present=True,to_sec_calls=spy.calls,exception=exception),
        ros_node_initialized_before=False,ros_node_initialized_after=rospy.core.is_initialized(),
        listener_created=False,ros_master_accessed=False,live_services_called=False,hardware_accessed=False,
        historical_data_or_qualification_rewritten=False,
        all_ten_arithmetic_and_installed_results_match_recorded=bool(len(rows)==10 and all(
            r['recorded_return_delta_ns']==r['arithmetic_cpp_rounding_delta_ns']==r['installed_identity_lookup_delta_ns'] for r in rows)),
        explanation='Camera read-completion stamps are generated by rospy.Time.now(); wallclock conversion truncates fractional nanoseconds from a time.time() double. These source stamps therefore already lie within one nanosecond below the double grid. tf2_py converts the query through to_sec() and C++ fromSec rounds the fractional nanoseconds, giving zero or plus one nanosecond here. Arbitrary integer stamps need not have this small error, as the deliberately shifted controls demonstrate.',
        source_code_reference='https://raw.githubusercontent.com/ros/geometry2/noetic-devel/tf2_py/src/tf2_py.cpp',
        script_summary='Read ten archived source timestamps; reproduce Python truncation and C++ positive rounding; perform installed BufferCore same-frame identity lookups and +37ns controls; probe to_sec dispatch with a raising spy. No ROS init_node, listener, publishers, subscribers, services or geometry replay.',
        pure_formula='sec,nsec=divmod(ns,10**9); f=sec+nsec/1e9; whole=floor(f); predicted_ns=whole*10**9+floor((f-whole)*1e9+.5)',
        limitations=['One nanosecond cannot explain the observed millimetre-scale cross-view discrepancy.',
            'This audit identifies software timestamp conversion only; it does not calibrate camera exposure time or prove physical pose accuracy.',
            'Historical nonexact TF flags and original accepted/excluded subsets remain unchanged.',
            'Changing the global tf2 library is not necessary work for this round and was not performed.'])
    if report['ros_node_initialized_after'] or spy.calls!=1:raise RuntimeError('offline conversion audit failed')
    a.output.mkdir()
    path=a.output/'report.json';path.write_text(json.dumps(report,ensure_ascii=False,indent=2,sort_keys=True)+'\n')
    (a.output/'SHA256SUMS').write_text(sha(path)+'  report.json\n')
    print(json.dumps(dict(report=str(path),sha256=sha(path),all_ten_match=report['all_ten_arithmetic_and_installed_results_match_recorded'],to_sec_calls=spy.calls)))
if __name__=='__main__':main()
